#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Markdown → Word (.docx)

Why not a JS library: python-docx is a mature solution that ships with the
environment here (1.2.0), whereas the Node ecosystem has no docx generation
library that handles both Chinese styles and tables well.

★ Output **must not contain any product attribution** (hard product rule):
  no footer, no "generated by ...", no watermark, no brand colors.
  Students must receive "their own document".

Usage:
  python md2docx.py input.md output.docx [title]
"""
from __future__ import annotations

import os
import re
import sys

from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Pt, RGBColor

# Chinese fonts must also set eastAsia, otherwise Word falls back to the default font for Chinese
BODY_FONT_CN = "等线"
BODY_FONT_EN = "Calibri"
HEAD_FONT_CN = "微软雅黑"
MONO_FONT = "Consolas"


def set_run_font(run, cn=BODY_FONT_CN, en=BODY_FONT_EN, size=None, bold=None, mono=False):
    if mono:
        cn = en = MONO_FONT
    run.font.name = en
    rpr = run._element.get_or_add_rPr()
    rfonts = rpr.find(qn("w:rFonts"))
    if rfonts is None:
        rfonts = rpr.makeelement(qn("w:rFonts"), {})
        rpr.append(rfonts)
    rfonts.set(qn("w:ascii"), en)
    rfonts.set(qn("w:hAnsi"), en)
    rfonts.set(qn("w:eastAsia"), cn)   # ★ this line is the key to making Chinese fonts take effect
    if size is not None:
        run.font.size = Pt(size)
    if bold is not None:
        run.font.bold = bold


# Inline syntax: `code`, **bold**, *italic*, [text](url), $formula$
INLINE_RE = re.compile(
    r"(`[^`]+`)"          # inline code
    r"|(\*\*[^*]+\*\*)"   # bold
    r"|(__[^_]+__)"       # bold (alternative syntax)
    r"|(\*[^*]+\*)"       # italic
    r"|(\$[^$\n]+\$)"     # inline formula (kept as-is; Word does not render LaTeX)
    r"|(\[[^\]]+\]\([^)]+\))"  # link
)


def add_inline(paragraph, text):
    """Write text containing inline markup into a paragraph, preserving bold/italic/code styles."""
    pos = 0
    for m in INLINE_RE.finditer(text):
        if m.start() > pos:
            r = paragraph.add_run(text[pos:m.start()])
            set_run_font(r)
        tok = m.group(0)
        if tok.startswith("`"):
            r = paragraph.add_run(tok[1:-1])
            set_run_font(r, mono=True, size=10)
        elif tok.startswith("**") or tok.startswith("__"):
            r = paragraph.add_run(tok[2:-2])
            set_run_font(r, bold=True)
        elif tok.startswith("*"):
            r = paragraph.add_run(tok[1:-1])
            set_run_font(r)
            r.font.italic = True
        elif tok.startswith("$"):
            r = paragraph.add_run(tok)          # keep formulas as-is; don't pretend to typeset them
            set_run_font(r, cn="Cambria Math", en="Cambria Math")
        elif tok.startswith("["):
            label = re.match(r"\[([^\]]+)\]", tok).group(1)
            url = re.match(r"\[[^\]]+\]\(([^)]+)\)", tok).group(1)
            r = paragraph.add_run(label)
            set_run_font(r)
            r.font.color.rgb = RGBColor(0x2F, 0x54, 0x96)
            r.font.underline = True
            _ = url  # hyperlink relationships need extra XML work; only apply styling for now
        pos = m.end()
    if pos < len(text):
        r = paragraph.add_run(text[pos:])
        set_run_font(r)


def convert(md_path: str, out_path: str, title: str | None = None) -> None:
    with open(md_path, "r", encoding="utf-8") as f:
        lines = f.read().replace("\r\n", "\n").split("\n")

    doc = Document()

    # Default body style
    normal = doc.styles["Normal"]
    normal.font.name = BODY_FONT_EN
    normal.font.size = Pt(10.5)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), BODY_FONT_CN)

    # Skip frontmatter
    i = 0
    if lines and lines[0].strip() == "---":
        i = 1
        while i < len(lines) and lines[i].strip() != "---":
            i += 1
        i += 1

    title_done = False
    in_fence = False
    fence_buf: list[str] = []
    table_buf: list[str] = []

    def flush_table():
        nonlocal table_buf
        if not table_buf:
            return
        rows = [
            [c.strip() for c in r.strip().strip("|").split("|")]
            for r in table_buf
        ]
        rows = [r for r in rows if not all(re.fullmatch(r":?-{2,}:?", c or "") for c in r)]
        if not rows:
            table_buf = []
            return
        cols = max(len(r) for r in rows)
        t = doc.add_table(rows=0, cols=cols)
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        for ri, row in enumerate(rows):
            cells = t.add_row().cells
            for ci in range(cols):
                txt = row[ci] if ci < len(row) else ""
                p = cells[ci].paragraphs[0]
                add_inline(p, txt)
                if ri == 0:
                    for r in p.runs:
                        r.font.bold = True
        doc.add_paragraph()
        table_buf = []

    def flush_fence():
        nonlocal fence_buf
        if not fence_buf:
            return
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Pt(18)
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(4)
        r = p.add_run("\n".join(fence_buf))
        set_run_font(r, mono=True, size=9.5)
        fence_buf = []

    while i < len(lines):
        line = lines[i]

        # Code block
        fm = re.match(r"^\s*(`{3,}|~{3,})", line)
        if fm:
            if not in_fence:
                flush_table()
                in_fence = True
                fence_buf = []
            else:
                flush_fence()
                in_fence = False
            i += 1
            continue
        if in_fence:
            fence_buf.append(line)
            i += 1
            continue

        # Table
        if re.match(r"^\s*\|.*\|\s*$", line):
            table_buf.append(line)
            i += 1
            continue
        if table_buf:
            flush_table()

        # Heading
        hm = re.match(r"^(#{1,6})\s+(.*)$", line)
        if hm:
            level = len(hm.group(1))
            text = hm.group(2).strip()
            if level == 1 and not title_done:
                # Use the document title rather than a normal heading style: clearer in Word's navigation pane
                h = doc.add_heading("", level=0)
                r = h.add_run(title or text)
                set_run_font(r, cn=HEAD_FONT_CN, en=HEAD_FONT_CN, size=20, bold=True)
                title_done = True
            else:
                h = doc.add_heading("", level=min(level, 4))
                r = h.add_run(text)
                sizes = {1: 18, 2: 15, 3: 13, 4: 12}
                set_run_font(r, cn=HEAD_FONT_CN, en=HEAD_FONT_CN, size=sizes.get(level, 11), bold=True)
            i += 1
            continue

        # Horizontal rule
        if re.match(r"^\s*([-*_])\s*\1\s*\1[\s\1]*$", line):
            p = doc.add_paragraph()
            r = p.add_run("─" * 30)
            set_run_font(r, size=8)
            r.font.color.rgb = RGBColor(0xAA, 0xAA, 0xAA)
            i += 1
            continue

        # Blockquote
        qm = re.match(r"^>\s?(.*)$", line)
        if qm:
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Pt(20)
            add_inline(p, qm.group(1))
            for r in p.runs:
                r.font.color.rgb = RGBColor(0x55, 0x55, 0x55)
            i += 1
            continue

        # Task list
        tm = re.match(r"^(\s*)[-*+]\s+\[([ xX])\]\s+(.*)$", line)
        if tm:
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Pt(18 + len(tm.group(1)) * 9)
            box = "☑ " if tm.group(2).lower() == "x" else "☐ "
            r = p.add_run(box)
            set_run_font(r)
            add_inline(p, tm.group(3))
            i += 1
            continue

        # Unordered list
        um = re.match(r"^(\s*)[-*+]\s+(.*)$", line)
        if um:
            p = doc.add_paragraph(style="List Bullet")
            p.paragraph_format.left_indent = Pt(18 + len(um.group(1)) * 9)
            add_inline(p, um.group(2))
            i += 1
            continue

        # Ordered list
        om = re.match(r"^(\s*)\d+[.)]\s+(.*)$", line)
        if om:
            p = doc.add_paragraph(style="List Number")
            p.paragraph_format.left_indent = Pt(18 + len(om.group(1)) * 9)
            add_inline(p, om.group(2))
            i += 1
            continue

        # Blank line
        if not line.strip():
            i += 1
            continue

        # Regular paragraph
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(6)
        add_inline(p, line)
        i += 1

    flush_table()
    flush_fence()

    os.makedirs(os.path.dirname(os.path.abspath(out_path)) or ".", exist_ok=True)
    doc.save(out_path)


def main() -> int:
    if len(sys.argv) < 3:
        print("Usage: python md2docx.py input.md output.docx [title]", file=sys.stderr)
        return 2
    src, dst = sys.argv[1], sys.argv[2]
    title = sys.argv[3] if len(sys.argv) > 3 else None
    try:
        convert(src, dst, title)
    except Exception as e:  # noqa: BLE001
        print(f"Conversion failed: {e}", file=sys.stderr)
        return 1
    print(f"OK {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
